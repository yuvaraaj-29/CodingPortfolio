    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
String cid = jTextField2.getText();
String cname = jTextField3.getText();
String cphone = jTextField4.getText();
String p = productid.getText();
int pid;

try {
    pid = Integer.parseInt(p);
} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this, "Invalid Product ID! Please enter a numeric value.", "Error", JOptionPane.ERROR_MESSAGE);
    return;
}

if (cid.isEmpty() && cname.isEmpty() && cphone.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Please enter Customer ID, Name, or Phone!", "Error", JOptionPane.ERROR_MESSAGE);
    return;
}

Connection con = null;
PreparedStatement customerStmt = null;
PreparedStatement productStmt = null;
ResultSet customerRs = null;
ResultSet productRs = null;

try {
    con = databaseconnection.getConnection();

    // Fetch customer details
    String customerQuery = "SELECT id, name, address, phone FROM customer WHERE ";
    if (!cid.isEmpty()) {
        customerQuery += "id = ?";
    } else if (!cname.isEmpty()) {
        customerQuery += "name = ?";
    } else if (!cphone.isEmpty()) {
        customerQuery += "phone = ?";
    }
    customerStmt = con.prepareStatement(customerQuery);
    if (!cid.isEmpty()) {
        customerStmt.setString(1, cid);
    } else if (!cname.isEmpty()) {
        customerStmt.setString(1, cname);
    } else if (!cphone.isEmpty()) {
        customerStmt.setString(1, cphone);
    }
    customerRs = customerStmt.executeQuery();
    if (customerRs.next()) {
        jTextField2.setText(customerRs.getString("id"));
        jTextField3.setText(customerRs.getString("name"));
        jTextArea1.setText(customerRs.getString("address"));
        jTextField4.setText(customerRs.getString("phone"));
    } else {
        JOptionPane.showMessageDialog(this, "Customer not found!", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    // Fetch product details
    String productQuery;

if (pid >= 100 && pid < 200) {
    productQuery = "SELECT r_id AS product_id, 1 AS quantity, price AS total_amount FROM racks WHERE r_id = ?";
} else if (pid >= 200 && pid < 500) {
    productQuery = "SELECT chair_id AS product_id, 1 AS quantity, total_price AS total_amount FROM chairs WHERE chair_id = ?";
} else if (pid >= 500 && pid < 700) {
    productQuery = "SELECT t_id AS product_id, 1 AS quantity, totalamt AS total_amount FROM tables WHERE t_id = ?";
} else if (pid >= 700 && pid < 900) {
    productQuery = "SELECT b_id AS product_id, 1 AS quantity, total AS total_amount FROM beds WHERE b_id = ?";
} else {
    JOptionPane.showMessageDialog(this, "Invalid Product ID range!", "Error", JOptionPane.ERROR_MESSAGE);
    return; // Exit as no valid range is matched
}

try {
    productStmt = con.prepareStatement(productQuery);
    productStmt.setString(1, p); // `p` is the product ID entered by the user
    productRs = productStmt.executeQuery();
    if (productRs.next()) {
        // Populate the fields with the fetched product details
        productid.setText(productRs.getString("product_id"));

        if (qty.getText().isEmpty()) {
            qty.setText(productRs.getString("quantity"));
        }
        if (price.getText().isEmpty()) {
            price.setText(productRs.getString("total_amount"));
        }
    } else {
        JOptionPane.showMessageDialog(this, "Product not found!", "Error", JOptionPane.ERROR_MESSAGE);
    }
} catch (Exception e) {
    JOptionPane.showMessageDialog(this, "Error fetching product details: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
}

} catch (Exception e) {
    e.printStackTrace();
    JOptionPane.showMessageDialog(this, "Error fetching details: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
}finally {
    try {
        if (customerRs != null) customerRs.close();
        if (productRs != null) productRs.close();
        if (customerStmt != null) customerStmt.close();
        if (productStmt != null) productStmt.close();
        if (con != null) con.close();
    } catch (Exception e) {
        e.printStackTrace();
    }
}
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
    String orderId = jLabel4.getText();
    String orderDateInput = jTextField1.getText(); 
    String customerId = jTextField2.getText();
    String productId = productid.getText();
    String productName = ptype.getText();
    String quantityStr = qty.getText();
    String totalAmountStr = price.getText();

    if (orderId.isEmpty() || orderDateInput.isEmpty() || customerId.isEmpty() ||
        productId.isEmpty() || productName.isEmpty() || quantityStr.isEmpty() || totalAmountStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please fill in all fields before placing the order!", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }
    try {
        SimpleDateFormat inputFormat = new SimpleDateFormat("MM/dd/yyyy"); 
        SimpleDateFormat outputFormat = new SimpleDateFormat("yyyy-MM-dd");
        Date date = inputFormat.parse(orderDateInput);
        String orderDate = outputFormat.format(date);
        int quantity = Integer.parseInt(quantityStr);
        double totalAmount = Double.parseDouble(totalAmountStr);
        Connection con = databaseconnection.getConnection();
        String insertOrderQuery = "INSERT INTO orders (order_id, order_date, customer_id, product_id, product_name, quantity,total_amount ) " +
                                  "VALUES (?, ?, ?, ?, ?, ?, ?)";
        PreparedStatement pst = con.prepareStatement(insertOrderQuery);
        pst.setString(1, orderId);
        pst.setString(2, orderDate); 
        pst.setString(3, customerId);
        pst.setString(4, productId);
        pst.setString(5, productName);
        pst.setInt(6, quantity);
        pst.setDouble(7, totalAmount);
        int rowsInserted = pst.executeUpdate();
        if (rowsInserted > 0) {
            JOptionPane.showMessageDialog(this, "successfully Added ");
            fetchNextOrderId();
        } else {
            JOptionPane.showMessageDialog(this, "Failed to place the order!", "Error", JOptionPane.ERROR_MESSAGE);
        }
        pst.close();
        con.close();
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Invalid date format! Please use MM/DD/YYYY.", "Error", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_jButton2ActionPerformed

