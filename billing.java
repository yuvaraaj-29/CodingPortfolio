      private void fetchNextOrderId() {
        try {
            Connection con = databaseconnection.getConnection();
            Statement stmt = con.createStatement();
            String query = "SELECT MAX(order_id) AS max_order_id FROM orders";
            ResultSet rs = stmt.executeQuery(query);
            if (rs.next()) {
                int nextOrderId = rs.getInt("max_order_id") + 1; 
                jLabel4.setText(String.valueOf(nextOrderId)); 
            } else {
                jLabel4.setText("1"); 
            }
            con.close();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error fetching next ORDER ID!", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }
